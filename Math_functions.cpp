#include <iostream>
#include<cmath>
int main(){
  double x=2;
  double y=3;
  std::cout<<std::max(x,y)<<"\n";
  std::cout<<std::min(x,y)<<"\n";
  std::cout<<pow(x,y)<<"\n";
  std::cout<<sqrt(9)<<"\n";
  std::cout<<abs(-3)<<"\n";
  std::cout<<round(2.33)<<"\n";
  std::cout<<ceil(2.33);
  return 0;

}